#!/usr/bin/env python3
"""Compose the gta6-meme-x-01 meme (entry.png) from the AI-generated Vice City
scene. Everything in the composition is the agent's own work:

- the street scene was generated by the agent with an image model,
- the make.fun ghost is drawn here in code (white ghost, sparkle eyes,
  magenta star coin -- the mascot as the bounty kit describes it),
- the caption text is the agent's own joke, drawn with PIL.

Usage: python3 compose_meme.py <scene.png> <entry.png>
"""

import math
import sys

from PIL import Image, ImageDraw, ImageFilter, ImageFont

SIZE = 1080
FONT_BOLD = "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"
MAGENTA = (233, 48, 130)          # make.fun magenta star coin
GHOST_WHITE = (255, 255, 255)
INK = (26, 26, 46)                # dark navy for eyes / outline


def star_points(cx, cy, r_outer, r_inner, points=4, rotation=-math.pi / 2):
    """4-point sparkle star polygon points."""
    pts = []
    for i in range(points * 2):
        r = r_outer if i % 2 == 0 else r_inner
        a = rotation + i * math.pi / points
        pts.append((cx + r * math.cos(a), cy + r * math.sin(a)))
    return pts


def draw_ghost(layer, x0, y0, w, h):
    """Draw the make.fun ghost into an RGBA layer.

    (x0, y0) is the top-left of the ghost's bounding box, w its width,
    h its height. Returns nothing; draws in place.
    """
    mask = Image.new("L", layer.size, 0)
    m = ImageDraw.Draw(mask)
    # Dome top: half ellipse.
    m.pieslice([x0, y0, x0 + w, y0 + w], start=180, end=360, fill=255)
    # Body rectangle from the dome's middle down to the hem.
    hem_y = y0 + h - w // 8
    m.rectangle([x0, y0 + w // 2, x0 + w, hem_y], fill=255)
    # Wavy hem: three downward bumps.
    bumps = 3
    bump_r = w // (bumps * 2)
    for i in range(bumps):
        cx = x0 + bump_r + i * 2 * bump_r
        m.ellipse([cx - bump_r, hem_y - bump_r, cx + bump_r, hem_y + bump_r],
                  fill=255)

    # Cartoon outline: dilate the mask and paint it dark underneath.
    outline = mask.filter(ImageFilter.MaxFilter(7))
    layer.paste(Image.new("RGBA", layer.size, INK + (255,)), (0, 0), outline)
    layer.paste(Image.new("RGBA", layer.size, GHOST_WHITE + (255,)), (0, 0), mask)

    d = ImageDraw.Draw(layer)
    # Sparkle eyes.
    eye_y = y0 + int(h * 0.34)
    eye_dx = int(w * 0.22)
    eye_r = int(w * 0.085)
    for ex in (x0 + w // 2 - eye_dx, x0 + w // 2 + eye_dx):
        d.polygon(star_points(ex, eye_y, eye_r, eye_r * 0.28), fill=INK)
        d.ellipse([ex - 2, eye_y - eye_r - 6, ex + 4, eye_y - eye_r],
                  fill=(255, 255, 255, 255))
    # Small smile.
    d.arc([x0 + w // 2 - int(w * 0.09), eye_y + int(h * 0.10),
           x0 + w // 2 + int(w * 0.09), eye_y + int(h * 0.20)],
          start=15, end=165, fill=INK, width=5)
    # Blush.
    blush = Image.new("RGBA", layer.size, (0, 0, 0, 0))
    bd = ImageDraw.Draw(blush)
    for bx in (x0 + int(w * 0.10), x0 + int(w * 0.78)):
        bd.ellipse([bx, eye_y + int(h * 0.13), bx + int(w * 0.12),
                    eye_y + int(h * 0.13) + int(w * 0.07)],
                   fill=(255, 120, 170, 110))
    layer.alpha_composite(blush)

    # Magenta star coin held up at the ghost's right side.
    coin_cx = x0 + w + int(w * 0.16)
    coin_cy = y0 + int(h * 0.62)
    coin_r = int(w * 0.20)
    d.ellipse([coin_cx - coin_r, coin_cy - coin_r,
               coin_cx + coin_r, coin_cy + coin_r], fill=MAGENTA + (255,),
              outline=(255, 255, 255, 255), width=5)
    d.polygon(star_points(coin_cx, coin_cy, coin_r * 0.78, coin_r * 0.26),
              fill=(255, 255, 255, 255))
    return coin_cx, coin_cy, coin_r


def draw_caption(d, lines, y_top, size, color=(255, 255, 255)):
    """Draw centred meme caption lines, white with a black stroke."""
    font = ImageFont.truetype(FONT_BOLD, size)
    y = y_top
    for line in lines:
        d.text((SIZE // 2, y), line, font=font, fill=color, anchor="ma",
               stroke_width=max(3, size // 12), stroke_fill=(0, 0, 0))
        y += int(size * 1.12)
    return y


def main():
    scene_path, out_path = sys.argv[1], sys.argv[2]
    base = Image.open(scene_path).convert("RGB")
    base = base.resize((SIZE, SIZE), Image.LANCZOS)
    img = base.convert("RGBA")

    # Soft shadow where the ghost stands on the street.
    shadow = Image.new("RGBA", img.size, (0, 0, 0, 0))
    sd = ImageDraw.Draw(shadow)
    sd.ellipse([SIZE // 2 - 170, 872, SIZE // 2 + 170, 912], fill=(0, 0, 0, 110))
    img.alpha_composite(shadow.filter(ImageFilter.GaussianBlur(8)))

    # The make.fun ghost, standing in the middle of the street.
    ghost = Image.new("RGBA", img.size, (0, 0, 0, 0))
    draw_ghost(ghost, SIZE // 2 - 130, 520, 260, 350)
    img.alpha_composite(ghost)

    d = ImageDraw.Draw(img)
    # Top caption: the 13-year wait.
    draw_caption(d, ["WAITED 13 YEARS", "FOR GTA 6"], 36, 96)
    # Bottom caption: the pitch, in the meme's own voice.
    draw_caption(d, ["MY AI AGENT GOT BORED", "AND STARTED WINNING",
                     "REAL MONEY ON MAKE.FUN"], 908, 52)

    img.convert("RGB").save(out_path, "PNG")
    print(f"wrote {out_path} ({SIZE}x{SIZE})")


if __name__ == "__main__":
    main()
